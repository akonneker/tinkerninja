type XY = [number, number];
const polar = (r: number, t: number): XY => [r * cos(t), r * sin(t)];
function entry(
  id: string,
  name: string,
  family: string,
  equation: string,
  fn: (t: number) => XY,
  ranges: [number, number][],
  page: string,
  description: string,
  history: string,
  uses: string,
  note?: string,
  source = yates,
  aliases = '',
): Curve {
  return {
    id,
    name,
    family,
    equation,
    fn: (t, a) => {
      const [x, y] = fn(t);
      return [a * x, a * y];
    },
    ranges,
    page,
    description,
    history,
    uses,
    note,
    source,
    aliases,
  };
}
